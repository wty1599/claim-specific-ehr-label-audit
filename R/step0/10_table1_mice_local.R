## ---------- 2. Helper functions ----------
first_existing <- function(dt, candidates) {
  x <- intersect(candidates, names(dt))
  if (length(x) == 0) return(NA_character_)
  x[1]
}

vec_num <- function(dt, candidates) {
  cn <- first_existing(dt, candidates)
  if (is.na(cn)) return(rep(NA_real_, nrow(dt)))
  suppressWarnings(as.numeric(dt[[cn]]))
}

vec_chr <- function(dt, candidates) {
  cn <- first_existing(dt, candidates)
  if (is.na(cn)) return(rep(NA_character_, nrow(dt)))
  as.character(dt[[cn]])
}

parse_sex <- function(x) {
  if (is.numeric(x)) return(as.integer(x == 1))
  x <- toupper(trimws(as.character(x)))
  fifelse(x %in% c("1", "M", "MALE"), 1L,
          fifelse(x %in% c("0", "F", "FEMALE"), 0L, NA_integer_))
}

parse_binary <- function(x) {
  if (is.numeric(x)) return(as.integer(x == 1))
  x <- tolower(trimws(as.character(x)))
  fifelse(x %in% c("1", "yes", "y", "true", "t", "male"), 1L,
          fifelse(x %in% c("0", "no", "n", "false", "f", "female"), 0L, NA_integer_))
}

med_iqr <- function(x) {
  x <- suppressWarnings(as.numeric(x))
  x <- x[is.finite(x)]
  if (length(x) == 0) return("—")
  q <- quantile(x, c(0.25, 0.50, 0.75), na.rm = TRUE, names = FALSE)
  sprintf("%.1f [%.1f, %.1f]", q[2], q[1], q[3])
}

n_pct <- function(x, positive = 1) {
  ok <- !is.na(x)
  if (!any(ok)) return("—")
  n <- sum(x[ok] == positive)
  d <- sum(ok)
  sprintf("%d (%.1f%%)", n, 100 * n / d)
}

safe_merge_one_to_one <- function(x, y, by, all.x = TRUE, name_y = "right table") {
  if (anyDuplicated(y[[by]]) > 0) stop("Duplicate IDs in ", name_y, ": ", by)
  merge(x, y, by = by, all.x = all.x)
}

