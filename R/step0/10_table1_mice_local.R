make_cont_summary <- function(var, section, characteristic) {
  out <- D[, .(value = med_iqr(get(var))), by = group]
  out[, `:=`(section = section, characteristic = characteristic)]
  out
}

make_bin_summary <- function(var, section, characteristic) {
  out <- D[, .(value = n_pct(get(var), 1)), by = group]
  out[, `:=`(section = section, characteristic = characteristic)]
  out
}

